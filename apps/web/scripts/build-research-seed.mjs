import { createHash } from "node:crypto"
import { mkdir, readFile, writeFile } from "node:fs/promises"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { ZodError } from "zod"

import { formatZodIssues, parseResearchSeed } from "./research-seed-schema.mjs"

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const appRoot = path.resolve(__dirname, "..")

const inputPath = path.resolve(
  appRoot,
  process.argv[2] ?? "src/db/seeds/research-companies.json"
)
const outputPath = path.resolve(
  appRoot,
  process.argv[3] ?? "src/db/seeds/research-companies.generated.sql"
)

function sqlString(value) {
  if (value === null || value === undefined || value === "") return "NULL"
  return `'${String(value).replaceAll("'", "''")}'`
}

function sqlJson(value) {
  if (value === null || value === undefined) return "NULL"
  return `${sqlString(JSON.stringify(value))}::jsonb`
}

function sqlTextArray(values) {
  if (!Array.isArray(values) || values.length === 0) return "NULL"
  return `ARRAY[${values.map(sqlString).join(", ")}]`
}

function stableUuid(key) {
  const hex = createHash("sha1").update(key).digest("hex").slice(0, 32).split("")
  hex[12] = "4"
  const variant = Number.parseInt(hex[16], 16)
  hex[16] = ((variant & 0x3) | 0x8).toString(16)
  return [
    hex.slice(0, 8).join(""),
    hex.slice(8, 12).join(""),
    hex.slice(12, 16).join(""),
    hex.slice(16, 20).join(""),
    hex.slice(20, 32).join(""),
  ].join("-")
}

function normalizeCompany(company) {
  const id = company.id ?? stableUuid(`company:${company.registeredName ?? company.name}`)
  return {
    ...company,
    id,
    shortName: company.shortName ?? company.name,
    city: company.city ?? "未知",
    industry: company.industry ?? "待分类",
    departments: company.departments?.length
      ? company.departments
      : ["研发与工程", "产品与设计", "商业化与运营"],
  }
}

function companyValues(company) {
  return [
    sqlString(company.id),
    sqlString(company.name),
    sqlString(company.registeredName),
    sqlString(company.shortName),
    sqlTextArray(company.aliases),
    sqlString(company.englishName),
    sqlString(company.unifiedSocialCreditCode),
    sqlString(company.registeredAddress),
    sqlString(company.legalRepresentative),
    sqlString(company.businessStatus),
    sqlString(company.foundedDate),
    sqlString(company.city),
    sqlString(company.industry),
    sqlString(company.size),
    sqlString(company.financingStage),
    sqlString(company.website),
    sqlString(company.logoUrl),
    sqlString(company.description),
    sqlJson(company.emailDomains ?? []),
    "'platform_seed'",
    "'reviewable'",
  ].join(", ")
}

function eventValues(company, event) {
  const eventId = event.id ?? stableUuid(`event:${company.id}:${event.date}:${event.title}`)
  return [
    sqlString(eventId),
    sqlString(company.id),
    sqlString(event.date),
    sqlString(event.title),
    sqlString(event.category ?? "其他"),
    sqlString(event.sourceUrl),
  ].join(", ")
}

function sentimentValues(company, point) {
  return [
    sqlString(company.id),
    sqlString(point.date),
    sqlString(point.score),
    Number.isFinite(point.sampleCount) ? String(point.sampleCount) : "0",
    sqlJson(point.components ?? {}),
  ].join(", ")
}

let seed
try {
  seed = parseResearchSeed(JSON.parse(await readFile(inputPath, "utf8")))
} catch (error) {
  if (error instanceof SyntaxError) {
    console.error(`Invalid JSON in ${path.relative(appRoot, inputPath)}: ${error.message}`)
    process.exit(1)
  }

  if (error instanceof ZodError) {
    console.error(`Research seed validation failed: ${path.relative(appRoot, inputPath)}`)
    console.error(formatZodIssues(error).join("\n"))
    process.exit(1)
  }
  throw error
}

const companies = seed.companies.map(normalizeCompany)

if (companies.length === 0) {
  throw new Error(`No companies found in ${inputPath}`)
}

const lines = [
  "-- Generated by scripts/build-research-seed.mjs",
  "-- Source: " + path.relative(appRoot, inputPath),
  "",
  "INSERT INTO companies (",
  "  id, name, registered_name, short_name, aliases, english_name,",
  "  unified_social_credit_code, registered_address, legal_representative, business_status, founded_date,",
  "  city, industry, size, financing_stage, website, logo_url, description, email_domains,",
  "  source, review_status",
  ")",
  "VALUES",
  companies.map((company) => `  (${companyValues(company)})`).join(",\n") + "\nON CONFLICT (id) DO UPDATE SET",
  "  name = EXCLUDED.name,",
  "  registered_name = EXCLUDED.registered_name,",
  "  short_name = EXCLUDED.short_name,",
  "  aliases = EXCLUDED.aliases,",
  "  english_name = EXCLUDED.english_name,",
  "  unified_social_credit_code = EXCLUDED.unified_social_credit_code,",
  "  registered_address = EXCLUDED.registered_address,",
  "  legal_representative = EXCLUDED.legal_representative,",
  "  business_status = EXCLUDED.business_status,",
  "  founded_date = EXCLUDED.founded_date,",
  "  city = EXCLUDED.city,",
  "  industry = EXCLUDED.industry,",
  "  size = EXCLUDED.size,",
  "  financing_stage = EXCLUDED.financing_stage,",
  "  website = EXCLUDED.website,",
  "  logo_url = EXCLUDED.logo_url,",
  "  description = EXCLUDED.description,",
  "  email_domains = EXCLUDED.email_domains,",
  "  source = EXCLUDED.source,",
  "  review_status = EXCLUDED.review_status,",
  "  updated_at = now();",
  "",
]

const departmentRows = companies.flatMap((company) =>
  company.departments.map((department) => `  (${sqlString(company.id)}, ${sqlString(department)}, '[]'::jsonb, 'active')`)
)
if (departmentRows.length > 0) {
  lines.push(
    "INSERT INTO departments (company_id, name, alias_names, status)",
    "VALUES",
    departmentRows.join(",\n") + "\nON CONFLICT (company_id, name) DO NOTHING;",
    ""
  )
}

const sentimentRows = companies.flatMap((company) =>
  (company.sentiment ?? []).map((point) => `  (${sentimentValues(company, point)})`)
)
if (sentimentRows.length > 0) {
  lines.push(
    "INSERT INTO company_sentiment_daily (company_id, date, score, sample_count, components)",
    "VALUES",
    sentimentRows.join(",\n") + "\nON CONFLICT (company_id, date) DO UPDATE SET",
    "  score = EXCLUDED.score,",
    "  sample_count = EXCLUDED.sample_count,",
    "  components = EXCLUDED.components,",
    "  updated_at = now();",
    ""
  )
}

const eventRows = companies.flatMap((company) =>
  (company.events ?? []).map((event) => `  (${eventValues(company, event)})`)
)
if (eventRows.length > 0) {
  lines.push(
    "INSERT INTO company_events (id, company_id, event_date, title, category, source_url)",
    "VALUES",
    eventRows.join(",\n") + "\nON CONFLICT (id) DO UPDATE SET",
    "  company_id = EXCLUDED.company_id,",
    "  event_date = EXCLUDED.event_date,",
    "  title = EXCLUDED.title,",
    "  category = EXCLUDED.category,",
    "  source_url = EXCLUDED.source_url;",
    ""
  )
}

await mkdir(path.dirname(outputPath), { recursive: true })
await writeFile(outputPath, lines.join("\n"), "utf8")

console.log(`Wrote ${path.relative(appRoot, outputPath)} from ${companies.length} companies`)
