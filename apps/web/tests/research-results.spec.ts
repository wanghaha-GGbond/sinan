import { expect, test } from "@playwright/test"

for (const width of [390, 1280]) for (const theme of ["light", "dark"]) {
  test(`research foreground contains results, not collection logs ${width}px ${theme}`, async ({ page }, testInfo) => {
    await page.route("**/api/auth/me", route => route.fulfill({ json: { user: null } }))
    await page.setViewportSize({ width, height: 844 })
    await page.addInitScript(theme => localStorage.setItem("sinan:theme", theme), theme)
    await page.goto("/research")
    await expect(page.getByRole("main")).toHaveCount(1)
    await expect(page.locator('a[href="/research/bytedance"] p').last()).toHaveCSS("word-break", "normal")
    const reports = page.locator('a[href^="/research/"]')
    await expect(reports).toHaveCount(10)
    await expect(page.getByText(/当前公开信号适合|待补采|条公开记录|可信度/)).toHaveCount(0)
    await page.screenshot({ path: testInfo.outputPath("research-list.png"), fullPage: true })
    await page.locator('a[href="/research/bytedance"]').click()
    await expect(page.getByRole("heading", { name: "字节跳动研究报告", exact: true })).toBeVisible()
    await expect(page.getByRole("main")).toHaveCount(1)
    if (theme === "dark") await expect(page.locator("html")).toHaveClass(/\bdark\b/)
    else await expect(page.locator("html")).not.toHaveClass(/\bdark\b/)
    const results = page.getByTestId("research-results")
    await expect(results.getByRole("heading").first()).toHaveText("机会与风险")
    await expect(results.getByText("AI 模型、生成式产品与云服务是明确的招聘机会方向", { exact: true })).toBeVisible()
    await expect(results.getByText("风险信息不足，尚不能判断。", { exact: true })).toBeVisible()
    await expect(results.getByText(/可信度|条证据|限制：|查看来源|暂无可读正文/)).toHaveCount(0)
    await expect(page.getByText(/建议先作为观察样本|再进入首屏|是内容社区样本/)).toHaveCount(0)
    const notes = page.getByTestId("research-notes")
    await expect(notes).not.toHaveAttribute("open", "")
    await expect(notes.getByRole("table")).toBeHidden()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: testInfo.outputPath("research-detail.png"), fullPage: true })
    await notes.locator("summary").focus()
    await page.keyboard.press("Enter")
    await expect(notes).toHaveAttribute("open", "")
    await expect(notes.getByRole("table")).toBeVisible()
    await expect(notes.getByRole("link", { name: "查看原文", exact: true }).first()).toHaveAttribute("href", /^https:\/\//)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  })
}

test("a supported company risk remains visible without a source wall", async ({ page }) => {
  await page.goto("/research/meituan")
  const results = page.getByTestId("research-results")
  await expect(results.getByText("即时零售竞争与阶段性亏损会提高业务目标和组织压力", { exact: true })).toBeVisible()
  await expect(results.getByText("风险信息不足，尚不能判断。", { exact: true })).toHaveCount(0)
  await expect(page.getByTestId("research-notes")).not.toHaveAttribute("open", "")
})
